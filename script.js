function showPost(type) {
  if (type === "code") {
    alert("Bài viết này chia sẻ các thói quen giúp bạn viết code sạch, dễ đọc và dễ bảo trì hơn.");
  } else if (type === "architecture") {
    alert("Bài viết này nói về cách kiến trúc ảnh hưởng đến trải nghiệm sống thông qua không gian, ánh sáng và vật liệu.");
  } else if (type === "revit") {
    alert("Bài viết này giới thiệu tư duy BIM và cách bắt đầu học Revit hiệu quả cho người mới.");
  }
}

